import fs from 'fs';
import path from 'path';
const root=process.cwd();
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const store=read('public/store/app.js');
const styles=read('public/store/styles.css');
const app=read('src/app.ts');
const orders=read('src/modules/orders/orders.routes.ts');
const payments=read('src/modules/payments/payments.routes.ts');
const commerce=read('src/services/global-commerce.service.ts');
const paypal=read('src/services/paypal.service.ts');
const readiness=read('src/modules/admin/readiness.routes.ts');
const publicAdmin=read('public/admin/app.js');
const pkg=JSON.parse(read('package.json'));
let failed=false;
const pass=m=>console.log(`PASS: ${m}`);
const fail=m=>{failed=true;console.error(`FAIL: ${m}`)};
const check=(c,m)=>c?pass(m):fail(m);
check(pkg.version==='2.5.2'&&app.includes("version: '2.5.2'"),'V2.5.2 package/runtime markers');
check(!store.includes('renderStripePayment')&&!store.includes('js.stripe.com')&&!store.includes("value:'stripe'")&&!/Stripe/i.test(store),'Stripe removed from customer-facing checkout and storefront copy');
check(!payments.includes('stripe: {')&&!payments.includes('Stripe Connect'),'payment config no longer exposes Stripe to website');
check(orders.includes("z.enum(['paypal', 'bank_transfer'])")&&!orders.includes('paymentIntents.create'),'orders checkout no longer creates Stripe payments');
check(!commerce.includes("result.push('stripe')")&&!commerce.includes("'stripe' | 'paypal'"),'global commerce no longer advertises Stripe checkout');
check(store.includes('components=buttons,googlepay,applepay'),'PayPal SDK loads PayPal + Google Pay + Apple Pay components');
check(store.includes('paypal.Googlepay()')&&store.includes('isReadyToPay')&&store.includes('confirmOrder')&&store.includes('initiatePayerAction'),'Google Pay eligibility, confirmation and 3DS flow');
check(store.includes('applepay.cdn-apple.com')&&store.includes('paypal.Applepay()')&&store.includes('canMakePayments')&&store.includes('validateMerchant')&&store.includes('ApplePaySession(4'),'Apple Pay eligibility and merchant validation flow');
check(app.includes("https://pay.google.com")&&app.includes("https://applepay.cdn-apple.com")&&!app.includes("'https://js.stripe.com'"),'CSP permits wallets and removes Stripe browser origins');
check(app.includes("/.well-known/apple-developer-merchantid-domain-association")&&app.includes("application/octet-stream"),'Apple Pay domain-association endpoint');
check(paypal.includes('Leave payment_source unset')&&paypal.includes("shipping_preference: 'SET_PROVIDED_ADDRESS'"),'wallet-neutral PayPal order with fixed shipping address');
check(readiness.includes("key:'GOOGLE_PAY_E2E'")&&readiness.includes("key:'APPLE_PAY_E2E'")&&readiness.includes("key:'MARKETPLACE_PAYOUTS'"),'wallet and marketplace readiness checks');
check(publicAdmin.includes('Google Pay')&&publicAdmin.includes('Apple Pay')&&!publicAdmin.includes('Stripe payout settings'),'admin website shows wallets without Stripe links');
check(styles.includes('apple-pay-button')&&styles.includes('.wallet-stack'),'wallet UI styling present');
check(!store.includes('PAYPAL_CLIENT_SECRET')&&!publicAdmin.includes('PAYPAL_CLIENT_SECRET'),'PayPal secret remains server-only');
if(failed)process.exit(1);
console.log('SANDMAN V2.5.2 wallet audit passed.');
